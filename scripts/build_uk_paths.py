"""Fit the route shapes of the UK map (`src/ttr/game/uk_paths.py`) to the printed board.

`assets/uk_cars.json` holds, for every route of the printed board, the centre of each car space (board pixels
of a 600x900 scan, the same units as the map data). Straight routes become a single segment; curved ones
(mostly ferries) become a smooth polyline fitted through the car centres. The two tracks of a double route
that run side by side share one line and are pushed apart by `side` (+1 / -1), like the Europe map.

    uv run python scripts/build_uk_paths.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
from numpy.polynomial import Polynomial

from ttr.game.uk_data import CITY_POS, UK_ROUTE_ENDS

ROOT = Path(__file__).resolve().parents[1]
CARS = ROOT / "scripts/assets/uk_cars.json"
OUT = ROOT / "src/ttr/game/uk_paths.py"
STRAIGHT = 4.5  # px: a route whose car centres stay this close to the chord is drawn straight
PARALLEL = 17.0  # px: double tracks closer than this (and of equal length) run side by side
STEP = 7.0  # px between points of a curved polyline

Point = tuple[float, float]


def _chain(track: dict, pos: dict[str, Point]) -> list[Point]:
    """Car centres ordered from city a to city b."""
    cars = [tuple(c) for c in track["cars"]]
    a = pos[track["a"]]
    if math.dist(a, cars[0]) > math.dist(a, cars[-1]):
        cars.reverse()
    return cars


def _fit(points: list[Point], degree: int) -> list[Point]:
    """Least-squares polynomial through the points (chord-length parameter), ends pinned."""
    p = np.array(points)
    t = np.concatenate([[0], np.cumsum(np.linalg.norm(np.diff(p, axis=0), axis=1))])
    t /= t[-1]
    w = np.ones(len(p))
    w[[0, -1]] = 50
    fx = Polynomial.fit(t, p[:, 0], degree, w=w)
    fy = Polynomial.fit(t, p[:, 1], degree, w=w)
    total = float(np.linalg.norm(np.diff(p, axis=0), axis=1).sum())
    n = max(2, round(total / STEP))
    ts = np.linspace(0, 1, n + 1)
    return list(zip(fx(ts), fy(ts), strict=True))


def _cross(u: np.ndarray, v: np.ndarray) -> float:
    return float(u[0] * v[1] - u[1] * v[0])


def _deviation(points: list[Point]) -> float:
    a, b = np.array(points[0]), np.array(points[-1])
    d = (b - a) / np.linalg.norm(b - a)
    return max(abs(_cross(d, np.array(q) - a)) for q in points)


def _shape(points: list[Point]) -> list[Point]:
    """Waypoints between the first and last point (empty = a straight line)."""
    if _deviation(points) <= STRAIGHT:
        return []
    mid = _fit(points, min(3 if len(points) < 8 else 4, len(points) - 2))[1:-1]
    return mid


def main() -> None:
    tracks = json.loads(CARS.read_text())
    pos = dict(CITY_POS)
    groups: dict[frozenset[str], list[dict]] = {}
    for t in tracks:
        groups.setdefault(frozenset((t["a"], t["b"])), []).append(t)
    out: dict[tuple[str, str], list[tuple[list[tuple[int, int]], int]]] = {}
    for tracks_ab in groups.values():
        a, b = tracks_ab[0]["a"], tracks_ab[0]["b"]
        ends = UK_ROUTE_ENDS.get((a, b))
        pa, pb = (ends[0], ends[1]) if ends else (pos[a], pos[b])
        chains = [[pa, *_chain(t, pos), pb] for t in tracks_ab]
        if len(tracks_ab) == 1:
            out[(a, b)] = [([(round(x), round(y)) for x, y in _shape(chains[0])], 0)]
            continue
        c0, c1 = chains
        side_by_side = len(c0) == len(c1) and np.mean([math.dist(p, q) for p, q in zip(c0, c1, strict=True)]) < PARALLEL
        if not side_by_side:  # e.g. Penzance-Plymouth: a land route and a ferry, each with its own shape
            out[(a, b)] = [([(round(x), round(y)) for x, y in _shape(ch)], 0) for ch in chains]
            continue
        centre = [((p[0] + q[0]) / 2, (p[1] + q[1]) / 2) for p, q in zip(c0, c1, strict=True)]
        mid = len(centre) // 2
        d = np.array(centre[mid + 1]) - np.array(centre[mid - 1])
        off = np.array(c0[mid]) - np.array(centre[mid])
        side0 = 1 if _cross(d, off) > 0 else -1  # +1 is to the left of the direction a -> b (screen y down)
        way = [(round(x), round(y)) for x, y in _shape(centre)]
        out[(a, b)] = [(way, side0), (way, -side0)]
    lines = ['"""Route shapes of the UK map (generated by `scripts/build_uk_paths.py`; board pixels)."""', ""]
    lines += ["# (city a, city b): per track in route order, (waypoints between the cities, side of a double track)"]
    lines += ["PATHS: dict[tuple[str, str], list[tuple[list[tuple[int, int]], int]]] = {"]
    for (a, b), tracks_out in out.items():
        lines.append(f'    ("{a}", "{b}"): {tracks_out!r},')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    curved = sum(1 for t in out.values() if t[0][0])
    print(f"wrote {OUT}: {len(out)} connections, {curved} curved")


if __name__ == "__main__":
    main()
